/// enigma_naming_audit.cpp
/// Naming coverage audit tool.
/// Categorizes every function by name prefix, hashes unnamed functions,
/// traverses the call graph to distinguish missing knowledge / discovery
/// failure / propagation failure, and emits both a human-readable report
/// and a CSV for cross-binary FID-candidate merging.
